"""Example 3 — live video from one window to the other (UDP).

Two windows, side by side:

* **side A** owns the camera. It shows what it captures and streams every
  picture, as a JPEG, to whoever is watching.
* **side B** subscribes to side A and shows the pictures as they arrive.

From the project root (after running the installer in toolchain/):

    .venv/bin/python examples/03_udp_video/main.py              # both windows, test pattern
    .venv/bin/python examples/03_udp_video/main.py --source 0   # both, first real camera
    .venv/bin/python examples/03_udp_video/main.py --poll       # both, always redraw
    .venv/bin/python examples/03_udp_video/main.py --side a     # only the camera side
    .venv/bin/python examples/03_udp_video/main.py --side b     # only the viewer side

The default source is ``test``: a moving pattern with a counter and a clock,
generated by side A, so the example runs on any machine without a camera and
without asking for camera permission. ``--source 0`` uses the first camera
(``1`` the second; a video file path works too).

Reactive is the default on both sides, exactly like example 2: the video
thread calls ``app.request_redraw()`` when a new picture is ready, and the
window draws once per picture. No picture, no frame.

------------------------------------------------------------------------------
How to configure link.toml
------------------------------------------------------------------------------
The same file as example 2: ``network/link.toml`` (or ``--config``). Side A is
the *server*, side B the *client*. Video uses its own UDP port, 50556.

1. Same machine — works out of the box (``server_ip = "127.0.0.1"``).

2. Two machines on the same local network:

   a. on the machine that runs side A (the camera): ``cd network && python3 -m udp_link ip``
   b. put that address in link.toml: ``server_ip = "192.168.1.50"``
   c. copy the **same** link.toml to both machines, then::

          machine A:  .venv/bin/python examples/03_udp_video/main.py --side a --source 0
          machine B:  .venv/bin/python examples/03_udp_video/main.py --side b

   The firewall of machine A must let UDP port 50556 in.

Optional video settings go in a ``[video]`` table of the same file::

       [video]
       port            = 50556
       max_subscribers = 4        # each viewer costs the full upload bandwidth

Too slow or blocky on Wi-Fi? Trade with ``--width 320 --height 240``,
``--fps 10`` or ``--quality 50`` on side A.

macOS and a real camera: the first ``--source 0`` run asks the terminal app for
camera permission. If no prompt appears and the camera stays closed, allow
your terminal in System Settings → Privacy & Security → Camera, then run again.
"""

from __future__ import annotations

import argparse
import logging
import subprocess
import sys
import threading
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "graphics"))  # the drawing library
sys.path.insert(0, str(ROOT / "network"))  # the udp + video libraries

DEFAULT_CONFIG = ROOT / "network" / "link.toml"

LABEL = (0.85, 0.92, 1.00)
ORANGE = (1.00, 0.55, 0.10, 1.0)
PANEL = (0.12, 0.12, 0.15, 1.0)
MARGIN = 12  # pixels around the picture
HEADER = 52  # room for the title panel
FOOTER = 34  # room for the status line

WINDOW = (560, 500)
GAP = 24  # pixels between the two windows
TOP_LEFT = (80, 120)  # where side A opens on the desktop


def make_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Stream video from side A to side B over UDP.",
    )
    parser.add_argument(
        "--side",
        choices=("a", "b", "both"),
        default="both",
        help="a = the camera side, b = the viewer, both = open the two (default)",
    )
    parser.add_argument(
        "--config",
        default=str(DEFAULT_CONFIG),
        help="link.toml to use (default: network/link.toml)",
    )
    camera = parser.add_argument_group("camera (side A)")
    camera.add_argument(
        "--source",
        default="test",
        help='"test" = moving pattern (default), 0 = first camera, or a video file',
    )
    camera.add_argument("--width", type=int, default=640)
    camera.add_argument("--height", type=int, default=480)
    camera.add_argument("--fps", type=float, default=15.0)
    camera.add_argument("--quality", type=int, default=70, help="JPEG quality 1-100")
    return parser


def open_side(side: str, parser: argparse.ArgumentParser):
    """The window of one side, placed so A and B sit next to each other."""
    import app3d

    x = TOP_LEFT[0] + (WINDOW[0] + GAP if side == "b" else 0)
    title = "side A — camera" if side == "a" else "side B — viewer"
    return app3d.App(title, size=WINDOW, position=(x, TOP_LEFT[1]), parser=parser)


class Screen:
    """The newest picture of a ``VideoThread``, as a texture, drawn to fit.

    One GPU texture is created for the first picture and then *updated*: the
    pixels change, the texture stays. That is what makes one picture per frame
    cheap. ``draw`` uploads a picture only when a new one has arrived.
    """

    def __init__(self, app, video) -> None:
        self.app = app
        self.video = video
        self.texture = None
        self.shown = 0  # video.frames at the last upload

    def draw(self) -> None:
        import screen2d
        from texture3d import Texture

        ui, video = self.app.aa, self.video
        width, height = self.app.size()
        box_anchor = (MARGIN, HEADER + MARGIN)
        box_size = (width - 2 * MARGIN, height - HEADER - FOOTER - 2 * MARGIN)
        ui.draw_screen_rect(box_anchor, box_size, PANEL, 10)  # where the picture goes

        picture = video.latest  # read once: the video thread may replace it
        if picture is None:
            return
        if video.frames != self.shown:  # a new picture since the last frame
            self.shown = video.frames
            if self.texture is None:
                self.texture = Texture(picture, mipmaps=False)
            else:
                self.texture.update(picture)

        # Keep the picture's proportions inside the box, whatever the window size.
        size = (self.texture.width, self.texture.height)
        anchor, fitted = screen2d.fit(size, box_anchor, box_size)
        ui.draw_screen_image(anchor, fitted, self.texture)

    def close(self) -> None:
        if self.texture is not None:
            self.texture.destroy()


def draw_labels(app, title: str, status: str, live: bool) -> None:
    """The header panel with its "live" dot, and the status line."""
    ui = app.aa
    width, height = app.size()
    ui.draw_screen_rect((MARGIN, MARGIN), (width - 2 * MARGIN, 40), PANEL, 10)
    ui.draw_screen_circle((MARGIN + 20, MARGIN + 20), 6, ORANGE if live else (0.35, 0.35, 0.4))
    ui.draw_screen_text(MARGIN + 38, MARGIN + 26, title, 14.0, LABEL)
    ui.draw_screen_text(MARGIN + 14, height - 16, status, 12.0, LABEL)


# ----------------------------------------------------------------- side A
def run_side_a(parser: argparse.ArgumentParser) -> None:
    """Owns the camera: capture, show the preview, stream to the viewers."""
    from video_link.bridge import VideoThread

    app = open_side("a", parser)
    args = app.args

    video = VideoThread(
        "server",
        args.config,
        source=args.source,
        width=args.width,
        height=args.height,
        fps=args.fps,
        quality=args.quality,
        # A new picture was captured: ask the window for one frame. This runs
        # in the video thread, so it only raises a flag and returns.
        on_frame=lambda _picture: app.request_redraw(),
    ).start()
    screen = Screen(app, video)

    def draw_frame() -> None:
        screen.draw()
        if video.error is not None:
            status = f"video error: {video.error}"
        else:
            status = (
                f"source {args.source}   frame {video.frames}   "
                f"viewers {video.viewers}   udp port {video.video.port}"
            )
        draw_labels(app, "SIDE A   camera", status, live=video.viewers > 0)

    try:
        app.run(draw_frame)
    finally:
        video.close()
        screen.close()


# ----------------------------------------------------------------- side B
def run_side_b(parser: argparse.ArgumentParser) -> None:
    """Shows what side A streams. It has no camera of its own."""
    from video_link.bridge import VideoThread

    app = open_side("b", parser)

    video = VideoThread(
        "client",
        app.args.config,
        on_frame=lambda _picture: app.request_redraw(),  # a picture arrived: draw it
    ).start()
    screen = Screen(app, video)

    def draw_frame() -> None:
        screen.draw()
        target = f"{video.link.server_ip}:{video.video.port}"
        if video.error is not None:
            status = f"video error: {video.error}"
        elif video.frames == 0:
            status = f"waiting for side A at {target} ..."
        else:
            status = (
                f"receiving from {target}   frame {video.frames}   "
                f"latency {video.latency * 1000:.0f} ms"
            )
        draw_labels(app, "SIDE B   viewer", status, live=video.frames > 0)

    try:
        app.run(draw_frame)
    finally:
        video.close()
        screen.close()


# ------------------------------------------------------------------- both
def run_both(argv: list[str]) -> int:
    """Open side A and side B as two processes, exactly as on two machines."""
    command = [sys.executable, str(Path(__file__).resolve())]
    side_a = subprocess.Popen([*command, *argv, "--side", "a"])
    time.sleep(0.4)  # let side A start listening, so side B subscribes at once
    side_b = subprocess.Popen([*command, *argv, "--side", "b"])
    children = (side_a, side_b)

    # Closing either window ends the demonstration: sleep until one exits.
    one_closed = threading.Event()
    for child in children:
        threading.Thread(
            target=lambda child=child: (child.wait(), one_closed.set()), daemon=True
        ).start()
    try:
        one_closed.wait()
    except KeyboardInterrupt:
        pass  # Ctrl+C reaches the two windows too: they close by themselves
    for child in children:
        if child.poll() is None:
            child.terminate()
    for child in children:
        child.wait()
    return 0


def main() -> int:
    parser = make_parser()
    side = parser.parse_known_args()[0].side  # the loop options are parsed by App
    if side == "both":
        return run_both(sys.argv[1:])
    logging.basicConfig(
        level=logging.INFO, format=f"side {side.upper()} %(levelname)-7s %(message)s"
    )
    (run_side_a if side == "a" else run_side_b)(parser)
    return 0


if __name__ == "__main__":
    sys.exit(main())
