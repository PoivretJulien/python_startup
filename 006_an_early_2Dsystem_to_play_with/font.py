"""A minimal single-stroke font: digits, the usual maths symbols, A-Z and a-z.

Glyphs are polylines in *em* units — baseline at ``y = 0``, cap height ``1.0``,
x-height ``0.62``, descenders down to ``-0.28`` — so a glyph is just a handful of
points and a width. Stroke fonts suit this project: the AA renderer already turns
any polyline into a distance-field capsule, so text needs no texture atlas, no
UVs, no second shader and no font file to ship.

If a character is missing, ``?`` is drawn instead; the set is meant to grow by
adding one line to ``GLYPHS``.

    advance/glyph widths  ->  ``advance()``, ``outline()``
    drawing               ->  ``renderer_aa.AAGridArrowRenderer.draw_text``
"""

from __future__ import annotations

import math

Point = tuple[float, float]
Shape = tuple[Point, ...]  # one polyline
Glyph = tuple[float, tuple[Shape, ...]]  # (advance in em, polylines)

CAP_HEIGHT = 1.0
X_HEIGHT = 0.62
DESCENDER = -0.28
SPACE_ADVANCE = 0.50
TRACKING = 0.04  # extra gap between glyphs, in em


def poly(*points: Point) -> Shape:
    """Name a polyline: ``poly((0, 0), (0, 1))`` reads better than a bare tuple."""
    return points


def arc(
    cx: float,
    cy: float,
    rx: float,
    ry: float,
    start_deg: float,
    end_deg: float,
    steps: int = 10,
) -> Shape:
    """Points along an elliptic arc. 0° = +x, angles grow counter-clockwise."""
    span = end_deg - start_deg
    return tuple(
        (
            cx + rx * math.cos(math.radians(start_deg + span * i / steps)),
            cy + ry * math.sin(math.radians(start_deg + span * i / steps)),
        )
        for i in range(steps + 1)
    )


def ring(cx: float, cy: float, rx: float, ry: float, steps: int = 14) -> Shape:
    """A closed ellipse: the arc returns to its first point, closing the stroke."""
    return arc(cx, cy, rx, ry, 0.0, 360.0, steps)


def mirror_x(shapes: tuple[Shape, ...], width: float) -> tuple[Shape, ...]:
    """Flip shapes horizontally inside ``width`` — how ``)`` ``]`` ``}`` are made."""
    return tuple(tuple((width - x, y) for x, y in shape) for shape in shapes)


